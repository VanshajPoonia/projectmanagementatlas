CREATE INDEX IF NOT EXISTS idx_crm_clients_status   ON public.crm_clients (status, last_activity_at DESC);
CREATE INDEX IF NOT EXISTS idx_crm_clients_sales_rep ON public.crm_clients (sales_rep_id);
-- The client list's search box hits name/company/email/phone; this covers the two on this
-- table. pg_trgm is not assumed to be installed, so it is a plain prefix-friendly lower() index.
CREATE INDEX IF NOT EXISTS idx_crm_clients_company  ON public.crm_clients (lower(company_name));

-- ── Contacts ─────────────────────────────────────────────────────────────────────────
-- "A client record can contain multiple individual contacts. Use + Add Customer for trusts,
-- families, partnerships, or other opportunities with multiple decision-makers."
CREATE TABLE IF NOT EXISTS public.crm_contacts (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id    UUID NOT NULL REFERENCES public.crm_clients(id) ON DELETE CASCADE,
  first_name   TEXT NOT NULL,
  last_name    TEXT NOT NULL,
  email        TEXT,
  mobile_phone TEXT,
  -- Exactly one primary per client is enforced by the partial unique index below.
  is_primary   BOOLEAN NOT NULL DEFAULT FALSE,
  position     INTEGER NOT NULL DEFAULT 0,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_crm_contacts_client ON public.crm_contacts (client_id, position);
CREATE INDEX IF NOT EXISTS idx_crm_contacts_email  ON public.crm_contacts (lower(email));
-- CASCADE here is correct and deliberate, unlike on the client: a contact is a part of its
-- client record, not an independent thing that should outlive it.
CREATE UNIQUE INDEX IF NOT EXISTS idx_crm_contacts_one_primary
  ON public.crm_contacts (client_id) WHERE is_primary;

-- ── Orders ───────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.crm_orders (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_no       TEXT UNIQUE,
  client_id      UUID NOT NULL REFERENCES public.crm_clients(id) ON DELETE CASCADE,
  order_type     TEXT NOT NULL DEFAULT 'standard',
  status         TEXT NOT NULL DEFAULT 'new' REFERENCES public.crm_statuses(key),
  owner_id       UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  priority       TEXT NOT NULL DEFAULT 'normal',
  estimated_value NUMERIC(14,2) NOT NULL DEFAULT 0,
  target_close_date DATE,
  opened_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Set by the trigger when the order first enters a terminal status, cleared if reopened.
  -- Stored rather than derived so "average days to close" is one scan, not a lateral join.
  closed_at      TIMESTAMPTZ,
  created_by     UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- ⚠️ Write-only carriers, never storage. The UI sets these in the SAME UPDATE that changes
  -- status; the trigger copies them onto the history row it opens and then blanks them again,
  -- so they are always NULL at rest. This is what lets a disposition be recorded atomically
  -- with the transition it describes: the alternative (a second write afterwards) leaves a
  -- window where the history says an order moved and cannot say why, and needs the history
  -- table to be application-writable, which is exactly what this module refuses to allow.
  status_change_reason TEXT,
  status_change_note   TEXT,
  CONSTRAINT crm_orders_priority_known CHECK (priority IN ('low', 'normal', 'high', 'urgent')),
  CONSTRAINT crm_orders_value_not_negative CHECK (estimated_value >= 0)
);

CREATE INDEX IF NOT EXISTS idx_crm_orders_client ON public.crm_orders (client_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_crm_orders_status ON public.crm_orders (status, opened_at);
CREATE INDEX IF NOT EXISTS idx_crm_orders_owner  ON public.crm_orders (owner_id, status);
-- The aging panel asks "open orders past their target close date", so both parts are indexed.
CREATE INDEX IF NOT EXISTS idx_crm_orders_open_target
  ON public.crm_orders (target_close_date) WHERE closed_at IS NULL;

-- ── Status history: the reporting spine ──────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.crm_order_status_history (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id    UUID NOT NULL REFERENCES public.crm_orders(id) ON DELETE CASCADE,
  status      TEXT NOT NULL REFERENCES public.crm_statuses(key),
  entered_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- NULL means "this is the interval the order is in right now". Exactly one open row per
  -- order, enforced by idx_crm_status_history_one_open below.
  exited_at   TIMESTAMPTZ,
  changed_by  UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  -- The "Reason / Disposition" dropdown: work proceeding normally, waiting on customer, etc.
  reason      TEXT,
  note        TEXT,
  CONSTRAINT crm_history_interval_ordered CHECK (exited_at IS NULL OR exited_at >= entered_at)
);

CREATE INDEX IF NOT EXISTS idx_crm_status_history_order
  ON public.crm_order_status_history (order_id, entered_at);
-- Cycle-time reporting scans by status and window; this is the index that report rides.
CREATE INDEX IF NOT EXISTS idx_crm_status_history_status
  ON public.crm_order_status_history (status, entered_at, exited_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_crm_status_history_one_open
  ON public.crm_order_status_history (order_id) WHERE exited_at IS NULL;

-- ── Notes and documents ──────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.crm_notes (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id  UUID NOT NULL REFERENCES public.crm_clients(id) ON DELETE CASCADE,
