-- ── Module registration ──────────────────────────────────────────────────────────────
-- Defaults OFF, like appointments (080): a module nobody has switched on must not appear in
-- everyone's navigation the moment this migration lands.
INSERT INTO public.app_modules (module_key, enabled)
VALUES ('crm', FALSE)
ON CONFLICT (module_key) DO NOTHING;

COMMENT ON TABLE public.crm_order_status_history IS
  'Append-only status intervals per order. Written only by private.crm_record_status_transition; '
  'authenticated holds SELECT and nothing else. Exactly one open (exited_at IS NULL) row per order.';

-- ── Post-conditions ──────────────────────────────────────────────────────────────────
DO $post$
DECLARE
  v_count   INTEGER;
  v_order   UUID;
  v_client  UUID;
  v_open    INTEGER;
  v_hist    INTEGER;
BEGIN
  SELECT count(*) INTO v_count FROM public.crm_statuses;
  IF v_count <> 8 THEN
    RAISE EXCEPTION '103 post-condition: expected 8 seeded statuses, found %', v_count;
  END IF;

  FOR v_count IN
    SELECT 1 FROM unnest(ARRAY['crm_statuses','crm_clients','crm_contacts','crm_orders',
                               'crm_order_status_history','crm_notes','crm_documents']) AS t(name)
    WHERE NOT (SELECT relrowsecurity FROM pg_class WHERE oid = ('public.' || t.name)::regclass)
  LOOP
    RAISE EXCEPTION '103 post-condition: RLS must be enabled on every crm table';
  END LOOP;

  -- anon must hold nothing anywhere in the module (095's rule, re-asserted per 097).
  IF EXISTS (
    SELECT 1 FROM unnest(ARRAY['crm_statuses','crm_clients','crm_contacts','crm_orders',
                               'crm_order_status_history','crm_notes','crm_documents']) AS t(name)
    WHERE has_table_privilege('anon', 'public.' || t.name, 'SELECT')
  ) THEN
    RAISE EXCEPTION '103 post-condition: anon must hold nothing on the crm tables';
  END IF;

  -- The audit trail must not be application-writable.
  IF has_table_privilege('authenticated', 'public.crm_order_status_history', 'INSERT')
     OR has_table_privilege('authenticated', 'public.crm_order_status_history', 'UPDATE')
     OR has_table_privilege('authenticated', 'public.crm_order_status_history', 'DELETE') THEN
    RAISE EXCEPTION '103 post-condition: status history must be SELECT-only for authenticated';
  END IF;

  -- Prove the trigger actually maintains the history, rather than trusting that it compiles.
  INSERT INTO public.crm_clients (company_name, client_type)
  VALUES ('__103_selftest__', 'business') RETURNING id INTO v_client;
  INSERT INTO public.crm_orders (client_id, order_no, status)
  VALUES (v_client, '__103_selftest__', 'new') RETURNING id INTO v_order;

  SELECT count(*) INTO v_hist FROM public.crm_order_status_history WHERE order_id = v_order;
  IF v_hist <> 1 THEN
    RAISE EXCEPTION '103 post-condition: INSERT must open exactly one interval, found %', v_hist;
  END IF;

  UPDATE public.crm_orders SET status = 'in_progress' WHERE id = v_order;
  UPDATE public.crm_orders
     SET status = 'won', status_change_reason = 'Work proceeding normally', status_change_note = 'self test'
   WHERE id = v_order;

  IF NOT EXISTS (
    SELECT 1 FROM public.crm_order_status_history
     WHERE order_id = v_order AND status = 'won'
       AND reason = 'Work proceeding normally' AND note = 'self test'
  ) THEN
    RAISE EXCEPTION '103 post-condition: the disposition must land on the interval it describes';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.crm_orders
     WHERE id = v_order
       AND (status_change_reason IS NOT NULL OR status_change_note IS NOT NULL)
  ) THEN
    RAISE EXCEPTION '103 post-condition: the status_change carriers must be blank at rest';
  END IF;

  SELECT count(*) INTO v_hist FROM public.crm_order_status_history WHERE order_id = v_order;
  SELECT count(*) INTO v_open FROM public.crm_order_status_history
   WHERE order_id = v_order AND exited_at IS NULL;
  IF v_hist <> 3 THEN
    RAISE EXCEPTION '103 post-condition: expected 3 intervals after 2 transitions, found %', v_hist;
  END IF;
  IF v_open <> 1 THEN
    RAISE EXCEPTION '103 post-condition: expected exactly 1 open interval, found %', v_open;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.crm_orders WHERE id = v_order AND closed_at IS NOT NULL) THEN
    RAISE EXCEPTION '103 post-condition: reaching a terminal status must stamp closed_at';
  END IF;

  -- Reopening must clear closed_at, or every cycle-time average is permanently wrong.
  UPDATE public.crm_orders SET status = 'in_progress' WHERE id = v_order;
  IF EXISTS (SELECT 1 FROM public.crm_orders WHERE id = v_order AND closed_at IS NOT NULL) THEN
    RAISE EXCEPTION '103 post-condition: reopening must clear closed_at';
  END IF;

  DELETE FROM public.crm_clients WHERE id = v_client;
  SELECT count(*) INTO v_hist FROM public.crm_order_status_history WHERE order_id = v_order;
  IF v_hist <> 0 THEN
    RAISE EXCEPTION '103 post-condition: deleting a client must cascade its order history';
  END IF;

  RAISE NOTICE '103 OK — crm schema ready, status-history trigger verified end to end';
END
