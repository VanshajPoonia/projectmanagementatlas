-- ── Clients ──────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.crm_clients (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  -- Human-facing "C-10482". Generated by claim_crm_client_ref() so two intakes racing cannot
  -- mint the same number; the same advisory-lock shape as project ids (migration 090).
  client_ref     TEXT UNIQUE,
  company_name   TEXT,
  client_type    TEXT NOT NULL DEFAULT 'individual',
  address        TEXT,
  city           TEXT,
  state          TEXT,
  postal_code    TEXT,
  lead_source    TEXT,
  status         TEXT NOT NULL DEFAULT 'new' REFERENCES public.crm_statuses(key),
  -- SET NULL, not CASCADE: deleting the person who owned an account must not delete the
  -- account. This is the same rule migration 100 had to retrofit onto boards and comments.
  sales_rep_id   UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  operations_rep_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  estimated_value NUMERIC(14,2) NOT NULL DEFAULT 0,
  notes          TEXT,
  created_by     UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_activity_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT crm_clients_type_known
    CHECK (client_type IN ('individual', 'business', 'family_trust', 'partner')),
  CONSTRAINT crm_clients_value_not_negative CHECK (estimated_value >= 0)
