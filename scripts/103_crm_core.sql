-- 103_crm_core.sql
--
-- The CRM module: clients, the contacts attached to them, orders, and — the part everything
-- else is built on — a full status transition history per order.
--
-- WHY A SEPARATE DOMAIN AND NOT boards/tasks. The obvious cheap move is "an order is a task on
-- a pipeline board, a status is a column". It was rejected deliberately:
--
--   * Every report the module exists to produce (New -> Closed cycle time, time-in-status,
--     bottleneck detection, SLA breach) needs an *entered/exited timestamp per status*. Tasks
--     record only their current column. There is nowhere to put the history without inventing
--     a task_status_history table, at which point "task" means two different things.
--   * An order needs a disposition on every transition and a mandatory reason on a losing one.
--     Columns cannot express either.
--   * lib/task-status.ts already carries scar tissue from the last time two status models were
--     reconciled by string matching (see CLAUDE.md §2). Adding a third meaning to `columns`
--     would repeat exactly that mistake.
--
-- WHY THE HISTORY IS WRITTEN BY A TRIGGER AND NOT THE CLIENT. The mockup's own stated
-- principle is "do not merely store the current status" — but a history the application is
-- trusted to append is a history that is wrong the first time any code path forgets. The
-- trigger below makes crm_orders.status and crm_order_status_history physically incapable of
-- disagreeing: the status column cannot change without closing the open interval and opening
-- the next one, in the same transaction as the UPDATE that caused it.
--
-- Purely additive: six new tables, one new enum-ish lookup table, one app_modules row. No
-- existing table, policy, grant or row is touched, so nothing that works today can break.
-- Paired rollback: scripts/rollback/103_revert.sql

BEGIN;

-- ── Statuses ─────────────────────────────────────────────────────────────────────────
-- A table rather than a CHECK constraint, mirroring public.task_statuses: the Administrator
-- role in the use-case doc "manages configuration", and renaming a stage must not be a
-- migration. `key` is the stable identifier reports group by; `label` is what humans see, and
-- is free to change without rewriting history.
CREATE TABLE IF NOT EXISTS public.crm_statuses (
  key            TEXT PRIMARY KEY,
  label          TEXT NOT NULL,
  position       INTEGER NOT NULL DEFAULT 0,
  -- Drives the pipeline board's colour and the dashboard tiles.
  color          TEXT NOT NULL DEFAULT '#6b7280',
  -- A terminal status stops the SLA clock: an order sitting in Won/Closed/Cancel is not
  -- "ageing", and counting it as such is what makes an aging report untrustworthy.
  is_terminal    BOOLEAN NOT NULL DEFAULT FALSE,
  -- Won vs Cancel are both terminal; only one of them counts toward conversion.
  is_won         BOOLEAN NOT NULL DEFAULT FALSE,
  -- "Lost Deal / Cancellation Reason * REQUIRED" in the intake mockup.
  requires_reason BOOLEAN NOT NULL DEFAULT FALSE,
  -- Hours in this status before the order is flagged on the aging panel. NULL = no target.
  sla_hours      INTEGER,
  is_archived    BOOLEAN NOT NULL DEFAULT FALSE,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

