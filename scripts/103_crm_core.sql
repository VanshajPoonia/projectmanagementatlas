  author_id  UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  body       TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_crm_notes_client ON public.crm_notes (client_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.crm_documents (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  client_id    UUID NOT NULL REFERENCES public.crm_clients(id) ON DELETE CASCADE,
  order_id     UUID REFERENCES public.crm_orders(id) ON DELETE CASCADE,
  storage_path TEXT NOT NULL,
  file_name    TEXT NOT NULL,
  mime_type    TEXT,
  size_bytes   BIGINT,
  uploaded_by  UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_crm_documents_client ON public.crm_documents (client_id, created_at DESC);

-- ── Reference generators ─────────────────────────────────────────────────────────────
-- Advisory-locked so two concurrent intakes cannot mint the same reference. Same shape as
-- claim_project_id (migration 090), which is where this pattern is already proven here.
CREATE OR REPLACE FUNCTION public.claim_crm_client_ref()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_next INTEGER;
BEGIN
  IF NOT private.is_active_user() THEN
    RAISE EXCEPTION 'not authorised to create clients' USING ERRCODE = '42501';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('crm_client_ref'));
  SELECT COALESCE(MAX(NULLIF(regexp_replace(client_ref, '\D', '', 'g'), '')::INTEGER), 10000) + 1
    INTO v_next FROM public.crm_clients WHERE client_ref ~ '^C-\d+$';
  RETURN 'C-' || v_next::TEXT;
END;
$$;
REVOKE ALL ON FUNCTION public.claim_crm_client_ref() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.claim_crm_client_ref() TO authenticated;

CREATE OR REPLACE FUNCTION public.claim_crm_order_no()
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_prefix TEXT;
  v_seq    INTEGER;
BEGIN
  IF NOT private.is_active_user() THEN
    RAISE EXCEPTION 'not authorised to create orders' USING ERRCODE = '42501';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtext('crm_order_no'));
  -- ORD-YYMMDD-#### matches the mockup's ORD-260813-1187.
  v_prefix := 'ORD-' || to_char(NOW(), 'YYMMDD');
  SELECT COALESCE(MAX(split_part(order_no, '-', 3)::INTEGER), 1000) + 1
    INTO v_seq FROM public.crm_orders WHERE order_no LIKE v_prefix || '-%';
  RETURN v_prefix || '-' || v_seq::TEXT;
END;
$$;
REVOKE ALL ON FUNCTION public.claim_crm_order_no() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.claim_crm_order_no() TO authenticated;

-- ── The transition trigger ───────────────────────────────────────────────────────────
-- This is what makes the history trustworthy. It runs on INSERT (open the first interval) and
-- on any UPDATE that changes status (close the open interval, open the next), so
-- crm_orders.status and the history cannot drift apart no matter which code path writes.
-- ⚠️ Three registrations, not one, because the timings genuinely differ:
--   BEFORE INSERT — may still edit NEW (stamp closed_at) but the row does not exist yet, so
--                   writing history here fails the order_id foreign key. The migration's own
--                   post-condition caught exactly that on the first run.
--   AFTER  INSERT — the row exists, so the opening interval can reference it.
--   BEFORE UPDATE — the row exists AND NEW is still editable, so one pass does both.
CREATE OR REPLACE FUNCTION private.crm_record_status_transition()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_terminal BOOLEAN;
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF TG_WHEN = 'BEFORE' THEN
      -- An order can be created already closed (backfilled/imported work).
      SELECT is_terminal INTO v_terminal FROM public.crm_statuses WHERE key = NEW.status;
      IF COALESCE(v_terminal, FALSE) AND NEW.closed_at IS NULL THEN
        NEW.closed_at := NEW.opened_at;
      END IF;
      RETURN NEW;
    END IF;

    INSERT INTO public.crm_order_status_history (order_id, status, entered_at, changed_by, reason, note)
    VALUES (NEW.id, NEW.status, NEW.opened_at, COALESCE(NEW.created_by, auth.uid()),
            NEW.status_change_reason, NEW.status_change_note);
    -- AFTER trigger: NEW is not writable here, so the carriers are cleared by a direct UPDATE
    -- that deliberately does not touch status (and so cannot re-enter this trigger).
    UPDATE public.crm_orders
       SET status_change_reason = NULL, status_change_note = NULL
     WHERE id = NEW.id
       AND (status_change_reason IS NOT NULL OR status_change_note IS NOT NULL);
    RETURN NULL;
  END IF;

  IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
    RETURN NEW;
  END IF;

  -- Close the interval the order is leaving. There is exactly one open row per order
  -- (idx_crm_status_history_one_open), so this cannot close the wrong one.
  UPDATE public.crm_order_status_history
     SET exited_at = NOW()
   WHERE order_id = NEW.id AND exited_at IS NULL;

  INSERT INTO public.crm_order_status_history (order_id, status, entered_at, changed_by, reason, note)
  VALUES (NEW.id, NEW.status, NOW(), auth.uid(), NEW.status_change_reason, NEW.status_change_note);

  -- BEFORE trigger, so blanking the carriers is just an assignment on the row being written.
  NEW.status_change_reason := NULL;
  NEW.status_change_note   := NULL;

  SELECT is_terminal INTO v_terminal FROM public.crm_statuses WHERE key = NEW.status;
  -- Reopening clears closed_at, so an order that comes back out of Won/Closed stops counting
  -- as closed instead of permanently skewing "average days to close".
  NEW.closed_at := CASE WHEN COALESCE(v_terminal, FALSE) THEN NOW() ELSE NULL END;
  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS crm_orders_status_history     ON public.crm_orders;
DROP TRIGGER IF EXISTS crm_orders_status_history_ins ON public.crm_orders;
DROP TRIGGER IF EXISTS crm_orders_status_history_new ON public.crm_orders;
DROP TRIGGER IF EXISTS crm_orders_status_history_upd ON public.crm_orders;

CREATE TRIGGER crm_orders_status_history_new
  BEFORE INSERT ON public.crm_orders
  FOR EACH ROW EXECUTE FUNCTION private.crm_record_status_transition();

CREATE TRIGGER crm_orders_status_history_ins
  AFTER INSERT ON public.crm_orders
  FOR EACH ROW EXECUTE FUNCTION private.crm_record_status_transition();

CREATE TRIGGER crm_orders_status_history_upd
  BEFORE UPDATE OF status ON public.crm_orders
  FOR EACH ROW EXECUTE FUNCTION private.crm_record_status_transition();

-- A transition on an order is activity on its client; the client list sorts by it.
CREATE OR REPLACE FUNCTION private.crm_touch_client()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE public.crm_clients
     SET last_activity_at = NOW()
   WHERE id = COALESCE(NEW.client_id, OLD.client_id);
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS crm_orders_touch_client ON public.crm_orders;
CREATE TRIGGER crm_orders_touch_client
  AFTER INSERT OR UPDATE ON public.crm_orders
  FOR EACH ROW EXECUTE FUNCTION private.crm_touch_client();

DROP TRIGGER IF EXISTS crm_notes_touch_client ON public.crm_notes;
CREATE TRIGGER crm_notes_touch_client
  AFTER INSERT ON public.crm_notes
  FOR EACH ROW EXECUTE FUNCTION private.crm_touch_client();

-- ── Grants and RLS ───────────────────────────────────────────────────────────────────
-- Supabase default-grants ALL on every new public table. 095 narrowed the defaults for tables
-- created by `postgres` (which the migration runner is), but the REVOKE is kept and asserted
-- below rather than assumed — the same reasoning as 097.
DO $grants$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'crm_statuses','crm_clients','crm_contacts','crm_orders',
    'crm_order_status_history','crm_notes','crm_documents'
  ] LOOP
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM anon', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM authenticated', t);
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END
$grants$;

GRANT SELECT ON public.crm_statuses TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.crm_clients   TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.crm_contacts  TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.crm_orders    TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.crm_notes     TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.crm_documents TO authenticated;
-- History is SELECT-only for everyone. It is written exclusively by the SECURITY DEFINER
-- trigger, which is the whole point: an audit trail an application can rewrite is not one.
-- UPDATE is granted on exited_at alone so nothing can retroactively edit what happened.
GRANT SELECT ON public.crm_order_status_history TO authenticated;

-- Statuses: everyone reads, admins configure.
DROP POLICY IF EXISTS "crm statuses readable" ON public.crm_statuses;
CREATE POLICY "crm statuses readable" ON public.crm_statuses
  FOR SELECT TO authenticated USING (private.is_active_user());

DROP POLICY IF EXISTS "crm statuses managed by admins" ON public.crm_statuses;
CREATE POLICY "crm statuses managed by admins" ON public.crm_statuses
  FOR ALL TO authenticated
  USING (private.is_admin_user()) WITH CHECK (private.is_admin_user());
GRANT INSERT, UPDATE, DELETE ON public.crm_statuses TO authenticated;

-- Clients / contacts / orders / notes / documents: this is a single-organisation product and
-- the CRM is a shared book of business, so every active member reads and writes it. Deleting
-- is deliberately narrowed to admins: a client record carries its orders and their history by
-- CASCADE, so an accidental delete destroys the reporting spine, not just a row.
DO $policies$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['crm_clients','crm_contacts','crm_orders','crm_notes','crm_documents'] LOOP
    EXECUTE format($p$DROP POLICY IF EXISTS "crm %1$s readable" ON public.%1$I$p$, t);
    EXECUTE format($p$CREATE POLICY "crm %1$s readable" ON public.%1$I
                      FOR SELECT TO authenticated USING (private.is_active_user())$p$, t);

    EXECUTE format($p$DROP POLICY IF EXISTS "crm %1$s insertable" ON public.%1$I$p$, t);
    EXECUTE format($p$CREATE POLICY "crm %1$s insertable" ON public.%1$I
                      FOR INSERT TO authenticated WITH CHECK (private.is_active_user())$p$, t);

    EXECUTE format($p$DROP POLICY IF EXISTS "crm %1$s updatable" ON public.%1$I$p$, t);
    EXECUTE format($p$CREATE POLICY "crm %1$s updatable" ON public.%1$I
                      FOR UPDATE TO authenticated
                      USING (private.is_active_user()) WITH CHECK (private.is_active_user())$p$, t);

    EXECUTE format($p$DROP POLICY IF EXISTS "crm %1$s deletable" ON public.%1$I$p$, t);
    EXECUTE format($p$CREATE POLICY "crm %1$s deletable" ON public.%1$I
                      FOR DELETE TO authenticated USING (private.is_admin_user())$p$, t);
  END LOOP;
END
$policies$;

